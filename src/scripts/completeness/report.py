def strongM_between(tome, a, b):
    n = 0
    for r in D['tomes'][str(tome)]:
        if a < r['i'] < b and r['cls'] == 'text' and r.get('cont', 0) >= 0.5 and r.get('nw', 0) >= 8:
            n += 1
    return n

