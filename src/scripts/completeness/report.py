def clean(s, n=80):
    s = re.sub(r'\s+', ' ', s or '').replace('|', '/')
    return s[:n]

def hd(h):
    return clean(h, 40) if h else '—'

def anchor(m):
    if not m:
        return '—'
    return f"{m['pid']} ({m['file']})"

